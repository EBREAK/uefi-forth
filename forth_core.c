#include "forth_core.h"
#include "forth.h"

void forth_init_core(void)
{
	DFWL(L"NOOP", O_NOOP);
	DESC(L"( -- ) \\ NOOP");
	ENDW();
	DFWL(L"HALT", O_HALT);
	DESC(L"( -- ) \\ FORTH SHUTDOWN");
	ENDW();
	DFWL(L"BRANCH", O_BRANCH);
	DESC(L"( -- ) \\ UNCOND BRANCH");
	ENDW();
	DFWL(L"ZBRANCH", O_ZBRANCH);
	DESC(L"( FLAG -- ) \\ BRANCH WHEN FLAG IS ZERO");
	ENDW();
	DFWL(L"EXIT", O_EXIT);
	ENDW();
	DFWL(L"CALL", O_CALL);
	COMPILE(L"EXIT");
	ENDW();
	DFWL(L"LIT", O_LIT);
	ENDW();
	DFWL(L"DOCONST", O_DOCONST);
	ENDW();
	CONSTANT(L"TRUE", FORTH_TRUE);
	ENDW();
	CONSTANT(L"FALSE", FORTH_FALSE);
	ENDW();
	DFWL(L"=CHK", O_EQCHK);
	ENDW();
	DFWL(L"EXECUTE", O_EXECUTE);
	ENDW();
	DFWL(L"PZCHK", O_PZCHK);
	ENDW();
	DFWL(L"DBGOFF", O_DBGOFF);
	ENDW();
	DFWL(L"DBGON", O_DBGON);
	ENDW();
	CONSTANT(L"$0", 0);
	ENDW();
	CONSTANT(L"$1", 1);
	ENDW();
	CONSTANT(L"$2", 2);
	ENDW();
	CONSTANT(L"$3", 3);
	ENDW();
	CONSTANT(L"$4", 4);
	ENDW();
	CONSTANT(L"$5", 5);
	ENDW();
	CONSTANT(L"$6", 6);
	ENDW();
	CONSTANT(L"$7", 7);
	ENDW();
	CONSTANT(L"$8", 8);
	ENDW();
	CONSTANT(L"$9", 9);
	ENDW();
	CONSTANT(L"$A", 0xA);
	ENDW();
	CONSTANT(L"$B", 0xB);
	ENDW();
	CONSTANT(L"$C", 0xC);
	ENDW();
	CONSTANT(L"$D", 0xD);
	ENDW();
	CONSTANT(L"$E", 0xE);
	ENDW();
	CONSTANT(L"$F", 0xF);
	ENDW();
	DFWL(L"DROP", O_DROP);
	ENDW();
	DFWL(L"DUP", O_DUP);
	ENDW();
	DFWL(L"SWAP", O_SWAP);
	ENDW();
	DFWL(L"NIP", O_NIP);
	ENDW();
	DFWL(L"OVER", O_OVER);
	ENDW();
	DFWL(L">R", O_TOR);
	ENDW();
	DFWL(L"R>", O_FROMR);
	ENDW();
	DFWL(L"PICK", O_PICK);
	ENDW();
	DFWL(L"DEPTH", O_DEPTH);
	ENDW();
	DFWH(L"ROT");
	// : ROT >R SWAP R> SWAP ;
	COMPILE(L">R", L"SWAP", L"R>", L"SWAP", L"EXIT");
	ENDW();
	DFWH(L"-ROT");
	// : -ROT SWAP >R SWAP R> ;
	COMPILE(L"SWAP", L">R", L"SWAP", L"R>", L"EXIT");
	ENDW();
	DFWH(L"2DROP");
	// : 2DROP DROP DROP ;
	COMPILE(L"DROP", L"DROP", L"EXIT");
	ENDW();
	DFWH(L"2DUP");
	// : 2DUP OVER OVER ;
	COMPILE(L"OVER", L"OVER", L"EXIT");
	ENDW();
	DFWH(L"2SWAP");
	// : 2SWAP >R -ROT R> -ROT ;
	COMPILE(L">R", L"-ROT", L"R>", L"-ROT", L"EXIT");
	ENDW();
	DFWH(L"2OVER");
	// : 2OVER >R >R 2DUP R> R> 2SWAP ;
	COMPILE(L">R", L">R", L"2DUP", L"R>", L"R>", L"2SWAP", L"EXIT");
	ENDW();
	DFWH(L"2ROT");
	// : 2ROT >R >R 2SWAP R> R> 2SWAP ;
	COMPILE(L">R", L">R", L"2SWAP", L"R>", L"R>", L"2SWAP", L"EXIT");
	ENDW();
	DFWH(L"2-ROT");
	// : 2-ROT 2SWAP >R >R 2SWAP R> R> ;
	COMPILE(L"2SWAP", L">R", L">R", L"2SWAP", L"R>", L"R>", L"EXIT");
	ENDW();

	DFWL(L"+", O_PLUS);
	ENDW();
	DFWL(L"1+", O_1PLUS);
	ENDW();
	DFWL(L"-", O_MINUS);
	ENDW();
	DFWL(L"1-", O_1MINUS);
	ENDW();
	DFWL(L"*", O_MULTI);
	ENDW();
	DFWL(L"2*", O_2MULTI);
	ENDW();
	DFWL(L"/", O_DIVID);
	ENDW();
	DFWL(L"2/", O_2DIVID);
	ENDW();
	DFWL(L"LSHIFT", O_LSHIFT);
	ENDW();
	DFWL(L"RSHIFT", O_RSHIFT);
	ENDW();
	DFWL(L"AND", O_AND);
	ENDW();
	DFWL(L"OR", O_OR);
	ENDW();
	DFWL(L"XOR", O_XOR);
	ENDW();
	DFWL(L"INVERT", O_INVERT);
	ENDW();
	DFWL(L"NEGATE", O_NEGATE);
	ENDW();
	DFWL(L"MOD", O_MOD);
	ENDW();

	DFWL(L"=", O_EQ);
	ENDW();
	DFWL(L"<>", O_NE);
	ENDW();
	DFWL(L"0=", O_EQZ);
	ENDW();
	DFWL(L"0<>", O_NEZ);
	ENDW();
	DFWL(L"<", O_LT);
	ENDW();
	DFWL(L">", O_GT);
	ENDW();
	DFWL(L"U<", O_ULT);
	ENDW();
	DFWL(L"U>", O_UGT);
	ENDW();

	DFWL(L"DP", O_DP);
	ENDW();
	DFWL(L"UP@", O_UPLOAD);
	ENDW();
	DFWL(L"STA@", O_STALOAD);
	ENDW();
	CONSTANT(L"FORTH-STA-PSER", FORTH_STA_PSER);
	ENDW();

	DFWL(L"C@", O_CLOAD);
	ENDW();
	DFWL(L"W@", O_WLOAD);
	ENDW();
	DFWL(L"L@", O_LLOAD);
	ENDW();
	DFWL(L"X@", O_XLOAD);
	ENDW();

	DFWH(L"HERE");
	COMPILE(L"DP", L"X@", L"EXIT");
	ENDW();
	DFWH(L"PAD");
	COMPILE(L"HERE");
	LIT(1024);
	COMPILE(L"+", L"EXIT");
	ENDW();

	DFWL(L"C!", O_CSTORE);
	ENDW();
	DFWL(L"W!", O_WSTORE);
	ENDW();
	DFWL(L"L!", O_LSTORE);
	ENDW();
	DFWL(L"X!", O_XSTORE);
	ENDW();

	DFWH(L"ALLOT");
	COMPILE(L"HERE", L"+", L"DP", L"X!", L"EXIT");
	ENDW();

	DFWH(L"C,");
	COMPILE(L"HERE", L"$1", L"ALLOT", L"C!", L"EXIT");
	ENDW();
	DFWH(L"W,");
	COMPILE(L"HERE", L"$2", L"ALLOT", L"W!", L"EXIT");
	ENDW();
	DFWH(L"L,");
	COMPILE(L"HERE", L"$4", L"ALLOT", L"L!", L"EXIT");
	ENDW();
	DFWH(L"X,");
	COMPILE(L"HERE", L"$8", L"ALLOT", L"X!", L"EXIT");
	ENDW();

	DFWL(L"PSP-RST", O_PSP_RST);
	ENDW();

	DFWL(L"EARLY-ECHO-OFF", O_EARLY_ECHO_OFF);
	ENDW();

	DFWL(L"EARLY-ECHO-ON", O_EARLY_ECHO_ON);
	ENDW();

	DFWL(L"TASK-NEW", O_TASK_NEW);
	DESC(L" ( IP -- TASK-ADDR )");
	ENDW();

	DFWL(L"CMOVE", O_CMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"WMOVE", O_WMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"LMOVE", O_LMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"XMOVE", O_XMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"CFILL", O_CFILL);
	DESC(L" ( ADDR COUNT CCHAR -- )");
	ENDW();
	DFWL(L"WFILL", O_WFILL);
	DESC(L" ( ADDR COUNT WCHAR -- )");
	ENDW();
	DFWL(L"LFILL", O_LFILL);
	DESC(L" ( ADDR COUNT LCHAR -- )");
	ENDW();
	DFWL(L"XFILL", O_XFILL);
	DESC(L" ( ADDR COUNT XCHAR -- )");
	ENDW();
}
