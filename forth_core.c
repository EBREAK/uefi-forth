#include "forth_core.h"
#include "forth.h"

void forth_init_core(void)
{
	DFWL(L"NOOP", O_NOOP);
	DESC(L"( -- ) \\ NOOP");
	ENDW();
	DFWL(L"HALT", O_HALT);
	DESC(L"( -- ) \\ FORTH SHUTDOWN");
	ENDW();
	DFWL(L"BRANCH", O_BRANCH);
	DESC(L"( -- ) \\ UNCOND BRANCH");
	ENDW();
	DFWL(L"ZBRANCH", O_ZBRANCH);
	DESC(L"( FLAG -- ) \\ BRANCH WHEN FLAG IS ZERO");
	ENDW();
	DFWL(L"EXIT", O_EXIT);
	DESC(L"( -- ) \\ UNEST");
	ENDW();
	DFWL(L"CALL", O_CALL);
	DESC(L"( -- ) \\ NEST");
	COMPILE(L"EXIT");
	ENDW();
	DFWL(L"LIT", O_LIT);
	DESC(L"( -- N ) \\ PUSH LITERAL N AFTER IP");
	ENDW();
	DFWL(L"DOCONST", O_DOCONST);
	DESC(L"( -- N ) \\ PUSH CONSTANT VALUE IN WORD BODY");
	ENDW();
	CONSTANT(L"TRUE", FORTH_TRUE);
	DESC(L"( -- TRUE ) \\ PUSH TRUE FLAG (-1)");
	ENDW();
	CONSTANT(L"FALSE", FORTH_FALSE);
	DESC(L"( -- FALSE ) \\ PUSH FALSE FLAG (0)");
	ENDW();
	DFWL(L"=CHK", O_EQCHK);
	DESC(L"( A B -- ) \\ ABORT IF A != B");
	ENDW();
	DFWL(L"EXECUTE", O_EXECUTE);
	DESC(L"( XT -- ) \\ EXECUTE XT");
	ENDW();
	DFWL(L"PZCHK", O_PZCHK);
	DESC(L"( -- ) \\ ABORT IF STACK NOT EMPTY");
	ENDW();
	DFWL(L"DBGOFF", O_DBGOFF);
	DESC(L"( -- ) \\ TURN DEBUG LOG OFF");
	ENDW();
	DFWL(L"DBGON", O_DBGON);
	DESC(L"( -- ) \\ TURN DEBUG LOG ON");
	ENDW();
	CONSTANT(L"$0", 0);
	DESC(L"( -- $0 ) \\ PUSH HEX CONSTANT 0");
	ENDW();
	CONSTANT(L"$1", 1);
	DESC(L"( -- $1 ) \\ PUSH HEX CONSTANT 1");
	ENDW();
	CONSTANT(L"$2", 2);
	DESC(L"( -- $2 ) \\ PUSH HEX CONSTANT 2");
	ENDW();
	CONSTANT(L"$3", 3);
	DESC(L"( -- $3 ) \\ PUSH HEX CONSTANT 3");
	ENDW();
	CONSTANT(L"$4", 4);
	DESC(L"( -- $4 ) \\ PUSH HEX CONSTANT 4");
	ENDW();
	CONSTANT(L"$5", 5);
	DESC(L"( -- $5 ) \\ PUSH HEX CONSTANT 5");
	ENDW();
	CONSTANT(L"$6", 6);
	DESC(L"( -- $6 ) \\ PUSH HEX CONSTANT 6");
	ENDW();
	CONSTANT(L"$7", 7);
	DESC(L"( -- $7 ) \\ PUSH HEX CONSTANT 7");
	ENDW();
	CONSTANT(L"$8", 8);
	DESC(L"( -- $8 ) \\ PUSH HEX CONSTANT 8");
	ENDW();
	CONSTANT(L"$9", 9);
	DESC(L"( -- $9 ) \\ PUSH HEX CONSTANT 9");
	ENDW();
	CONSTANT(L"$A", 0xA);
	DESC(L"( -- $A ) \\ PUSH HEX CONSTANT 10");
	ENDW();
	CONSTANT(L"$B", 0xB);
	DESC(L"( -- $B ) \\ PUSH HEX CONSTANT 11");
	ENDW();
	CONSTANT(L"$C", 0xC);
	DESC(L"( -- $C ) \\ PUSH HEX CONSTANT 12");
	ENDW();
	CONSTANT(L"$D", 0xD);
	DESC(L"( -- $D ) \\ PUSH HEX CONSTANT 13");
	ENDW();
	CONSTANT(L"$E", 0xE);
	DESC(L"( -- $E ) \\ PUSH HEX CONSTANT 14");
	ENDW();
	CONSTANT(L"$F", 0xF);
	DESC(L"( -- $F ) \\ PUSH HEX CONSTANT 15");
	ENDW();
	DFWL(L"DROP", O_DROP);
	DESC(L"( N -- ) \\ DROP TOP ITEM");
	ENDW();
	DFWL(L"DUP", O_DUP);
	DESC(L"( N -- N N ) \\ DUPLICATE TOP ITEM");
	ENDW();
	DFWL(L"SWAP", O_SWAP);
	DESC(L"( A B -- B A ) \\ SWAP TOP TWO ITEMS");
	ENDW();
	DFWL(L"NIP", O_NIP);
	DESC(L"( A B -- B ) \\ DROP SECOND ITEM");
	ENDW();
	DFWL(L"OVER", O_OVER);
	DESC(L"( A B -- A B A ) \\ COPY SECOND ITEM");
	ENDW();
	DFWL(L">R", O_TOR);
	DESC(L"( N -- ) \\ PUSH TOP TO RETURN STACK");
	ENDW();
	DFWL(L"R>", O_FROMR);
	DESC(L"( -- N ) \\ POP FROM RETURN STACK");
	ENDW();
	DFWL(L"PICK", O_PICK);
	DESC(L"( ... N -- ... ITEM ) \\ PICK NTH ITEM");
	ENDW();
	DFWL(L"DEPTH", O_DEPTH);
	DESC(L"( -- N ) \\ GET STACK USED ITEMS");
	ENDW();
	DFWH(L"ROT");
	DESC(L"( A B C -- B C A ) \\ ROTATE");
	// : ROT >R SWAP R> SWAP ;
	COMPILE(L">R", L"SWAP", L"R>", L"SWAP", L"EXIT");
	ENDW();
	DFWH(L"-ROT");
	DESC(L"( A B C -- C A B ) \\ REV ROTATE");
	// : -ROT SWAP >R SWAP R> ;
	COMPILE(L"SWAP", L">R", L"SWAP", L"R>", L"EXIT");
	ENDW();
	DFWH(L"2DROP");
	DESC(L"( A B -- ) \\ DROP TOP TWO ITEMS");
	// : 2DROP DROP DROP ;
	COMPILE(L"DROP", L"DROP", L"EXIT");
	ENDW();
	DFWH(L"2DUP");
	DESC(L"( A B -- A B A B ) \\ DUPLICATE TOP TWO ITEMS");
	// : 2DUP OVER OVER ;
	COMPILE(L"OVER", L"OVER", L"EXIT");
	ENDW();
	DFWH(L"2SWAP");
	DESC(L"( A B C D -- C D A B ) \\ SWAP TOP TWO ITEMS");
	// : 2SWAP >R -ROT R> -ROT ;
	COMPILE(L">R", L"-ROT", L"R>", L"-ROT", L"EXIT");
	ENDW();
	DFWH(L"2OVER");
	DESC(L"( A B C D -- A B C D A B )");
	// : 2OVER >R >R 2DUP R> R> 2SWAP ;
	COMPILE(L">R", L">R", L"2DUP", L"R>", L"R>", L"2SWAP", L"EXIT");
	ENDW();
	DFWH(L"2ROT");
	DESC(L"( A B C D E F -- C D E F A B )");
	// : 2ROT >R >R 2SWAP R> R> 2SWAP ;
	COMPILE(L">R", L">R", L"2SWAP", L"R>", L"R>", L"2SWAP", L"EXIT");
	ENDW();
	DFWH(L"2-ROT");
	DESC(L"( A B C D E F -- E F A B C D )");
	// : 2-ROT 2SWAP >R >R 2SWAP R> R> ;
	COMPILE(L"2SWAP", L">R", L">R", L"2SWAP", L"R>", L"R>", L"EXIT");
	ENDW();

	DFWL(L"+", O_PLUS);
	DESC(L"( A B -- A+B )");
	ENDW();
	DFWL(L"1+", O_1PLUS);
	DESC(L"( N -- N+1 )");
	ENDW();
	DFWL(L"-", O_MINUS);
	DESC(L"( A B -- A-B )");
	ENDW();
	DFWL(L"1-", O_1MINUS);
	DESC(L"( N -- N-1 )");
	ENDW();
	DFWL(L"*", O_MULTI);
	DESC(L"( A B -- A*B )");
	ENDW();
	DFWL(L"2*", O_2MULTI);
	DESC(L"( N -- N*2 )");
	ENDW();
	DFWL(L"/", O_DIVID);
	DESC(L"( A B -- A/B )");
	ENDW();
	DFWL(L"2/", O_2DIVID);
	DESC(L"( N -- N/2 )");
	ENDW();
	DFWL(L"LSHIFT", O_LSHIFT);
	DESC(L"( N S -- N<<S )");
	ENDW();
	DFWL(L"RSHIFT", O_RSHIFT);
	DESC(L"( N S -- N>>S )");
	ENDW();
	DFWL(L"AND", O_AND);
	DESC(L"( A B -- A&B )");
	ENDW();
	DFWL(L"OR", O_OR);
	DESC(L"( A B -- A|B )");
	ENDW();
	DFWL(L"XOR", O_XOR);
	DESC(L"( A B -- A^B )");
	ENDW();
	DFWL(L"INVERT", O_INVERT);
	DESC(L"( N -- ~N )");
	ENDW();
	DFWL(L"NEGATE", O_NEGATE);
	DESC(L"( N -- -N )");
	ENDW();
	DFWL(L"MOD", O_MOD);
	DESC(L"( A B -- A%B )");
	ENDW();

	DFWL(L"=", O_EQ);
	DESC(L"( A B -- FLAG ) \\ TEST TOP TWO EQUAL");
	ENDW();
	DFWL(L"<>", O_NE);
	DESC(L"( A B -- FLAG ) \\ TEST TOP TWO NOT EQUAL");
	ENDW();
	DFWL(L"0=", O_EQZ);
	DESC(L"( N -- FLAG ) \\ TEST TOP IS ZERO");
	ENDW();
	DFWL(L"0<>", O_NEZ);
	DESC(L"( N -- FLAG ) \\ TEST TOP NOT ZERO");
	ENDW();
	DFWL(L"<", O_LT);
	DESC(L"( A B -- FLAG ) \\ TEST SECOND < TOP");
	ENDW();
	DFWL(L">", O_GT);
	DESC(L"( A B -- FLAG ) \\ TEST SECOND > TOP");
	ENDW();
	DFWL(L"U<", O_ULT);
	DESC(L"( A B -- FLAG ) \\ TEST SECOND U< TOP");
	ENDW();
	DFWL(L"U>", O_UGT);
	DESC(L"( A B -- FLAG ) \\ TEST SECOND U> TOP");
	ENDW();

	DFWL(L"DP", O_DP);
	DESC(L"( -- ADDR ) \\ GET DICT POINTER");
	ENDW();
	DFWL(L"UP@", O_UPLOAD);
	DESC(L"( -- ADDR ) \\ GET USER POINTER");
	ENDW();
	DFWL(L"STA@", O_STALOAD);
	DESC(L"( -- STA ) \\ GET STATUS REGISTER");
	ENDW();
	CONSTANT(L"FORTH-STA-PSER", FORTH_STA_PSER);
	DESC(L"( -- MASK ) \\ STA REG PARAM STACK ERROR MASK VALUE");
	ENDW();

	DFWL(L"C@", O_CLOAD);
	DESC(L"( ADDR -- C ) \\ FETCH 8BIT  FROM ADDR");
	ENDW();
	DFWL(L"W@", O_WLOAD);
	DESC(L"( ADDR -- W ) \\ FETCH 16BIT FROM ADDR");
	ENDW();
	DFWL(L"L@", O_LLOAD);
	DESC(L"( ADDR -- L ) \\ FETCH 32BIT FROM ADDR");
	ENDW();
	DFWL(L"X@", O_XLOAD);
	DESC(L"( ADDR -- X ) \\ FETCH 64BIT FROM ADDR");
	ENDW();

	DFWH(L"HERE");
	DESC(L"( -- ADDR ) \\ GET DICT HERE");
	COMPILE(L"DP", L"X@", L"EXIT");
	ENDW();
	DFWH(L"PAD");
	DESC(L"( -- ADDR ) \\ GET PAD BUFFER ADDR");
	COMPILE(L"HERE");
	LIT(1024);
	COMPILE(L"+", L"EXIT");
	ENDW();

	DFWL(L"C!", O_CSTORE);
	DESC(L"( C ADDR -- ) \\ STORE 8BIT  TO ADDR");
	ENDW();
	DFWL(L"W!", O_WSTORE);
	DESC(L"( W ADDR -- ) \\ STORE 16BIT TO ADDR");
	ENDW();
	DFWL(L"L!", O_LSTORE);
	DESC(L"( L ADDR -- ) \\ STORE 32BIT TO ADDR");
	ENDW();
	DFWL(L"X!", O_XSTORE);
	DESC(L"( X ADDR -- ) \\ STORE 64BIT TO ADDR");
	ENDW();

	DFWH(L"ALLOT");
	DESC(L"( N -- ) \\ ALLOCATE N BYTES");
	COMPILE(L"HERE", L"+", L"DP", L"X!", L"EXIT");
	ENDW();

	DFWH(L"C,");
	DESC(L"( C -- ) \\ APPEND 8BIT  TO DICT");
	COMPILE(L"HERE", L"$1", L"ALLOT", L"C!", L"EXIT");
	ENDW();
	DFWH(L"W,");
	DESC(L"( W -- ) \\ APPEND 16BIT TO DICT");
	COMPILE(L"HERE", L"$2", L"ALLOT", L"W!", L"EXIT");
	ENDW();
	DFWH(L"L,");
	DESC(L"( L -- ) \\ APPEND 32BIT TO DICT");
	COMPILE(L"HERE", L"$4", L"ALLOT", L"L!", L"EXIT");
	ENDW();
	DFWH(L"X,");
	DESC(L"( X -- ) \\ APPEND 64BIT TO DICT");
	COMPILE(L"HERE", L"$8", L"ALLOT", L"X!", L"EXIT");
	ENDW();

	DFWL(L"PSP-RST", O_PSP_RST);
	DESC(L"( -- ) \\ RESET PARAM STACK");
	ENDW();

	DFWL(L"EARLY-ECHO-OFF", O_EARLY_ECHO_OFF);
	DESC(L"( -- ) \\ TURN EARLY ECHO OFF");
	ENDW();

	DFWL(L"EARLY-ECHO-ON", O_EARLY_ECHO_ON);
	DESC(L"( -- ) \\ TURN EARLY ECHO ON");
	ENDW();

	DFWL(L"EARLY-CLR", O_EARLY_CLR);
	DESC(L"( -- ) \\ CLEAR EARLY CON");
	ENDW();

	DFWL(L"TASK-NEW", O_TASK_NEW);
	DESC(L" ( IP -- TASK-ADDR )");
	ENDW();

	DFWL(L"CMOVE", O_CMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"WMOVE", O_WMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"LMOVE", O_LMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"XMOVE", O_XMOVE);
	DESC(L" ( SRC-ADDR DST-ADDR COUNT -- )");
	ENDW();
	DFWL(L"CFILL", O_CFILL);
	DESC(L" ( ADDR COUNT CCHAR -- )");
	ENDW();
	DFWL(L"WFILL", O_WFILL);
	DESC(L" ( ADDR COUNT WCHAR -- )");
	ENDW();
	DFWL(L"LFILL", O_LFILL);
	DESC(L" ( ADDR COUNT LCHAR -- )");
	ENDW();
	DFWL(L"XFILL", O_XFILL);
	DESC(L" ( ADDR COUNT XCHAR -- )");
	ENDW();

	DFWL(L"ALLOCATE", O_ALLOCATE);
	DESC(L" ( COUNT -- 0|ADDR )");
	ENDW();

	DFWL(L"FREE", O_FREE);
	DESC(L" ( ADDR -- )");
	ENDW();
}
